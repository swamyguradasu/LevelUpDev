/**
 * Returns today's date formatted in 'YYYY-MM-DD' according to the Asia/Kolkata timezone.
 */
export function getISTDateString(date: Date = new Date()): string {
  try {
    return new Intl.DateTimeFormat('en-CA', {
      timeZone: 'Asia/Kolkata',
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
    }).format(date);
  } catch {
    return date.toISOString().split('T')[0];
  }
}

/**
 * Returns a human-friendly formatted date in IST, e.g. "September 2, 2026".
 */
export function getISTFormattedDate(dateStr?: string): string {
  try {
    let date: Date;
    if (dateStr) {
      const [y, m, d] = dateStr.split('-').map(Number);
      date = new Date(Date.UTC(y, m - 1, d, 12, 0, 0));
    } else {
      date = new Date();
    }
    return new Intl.DateTimeFormat('en-US', {
      timeZone: 'Asia/Kolkata',
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    }).format(date);
  } catch {
    return dateStr || new Date().toDateString();
  }
}

/**
 * Calculates days between a target date string and the curriculum start date.
 */
export function getDaysDifference(targetDateStr: string, startDateStr: string = CURRICULUM_START_DATE): number {
  const [ty, tm, td] = targetDateStr.split('-').map(Number);
  const [sy, sm, sd] = startDateStr.split('-').map(Number);

  const targetUtc = Date.UTC(ty, tm - 1, td);
  const startUtc = Date.UTC(sy, sm - 1, sd);

  const diffMs = targetUtc - startUtc;
  return Math.floor(diffMs / (1000 * 60 * 60 * 24));
}

export interface DateChallengeSelection {
  challenge: DailyChallenge;
  sequenceNumber: number;
  dayNumber: number;
  totalDays: number;
  cycle: number;
  isCycleCompleted: boolean;
  isPreview: boolean;
  dateStr: string;
  formattedDate: string;
}

/**
 * Deterministically select the daily challenge for a given date in IST.
 * - Start Date: 2026-09-02 -> Problem #1 (Two Sum)
 * - 2026-09-03 -> Problem #2 (Contains Duplicate)
 * - After 268 days: Cycle increments and completion banner is triggered.
 */
export function getDailyChallengeByDate(targetDateStr?: string): DateChallengeSelection {
  const dateStr = targetDateStr || getISTDateString();
  const diffDays = getDaysDifference(dateStr, CURRICULUM_START_DATE);

  const totalCurriculum = DAILY_CHALLENGES.length; // 268

  if (diffDays < 0) {
    // Before start date (e.g. today Sep 1, 2026) -> Preview of Day 1
    const challenge = DAILY_CHALLENGES[0];
    return {
      challenge,
      sequenceNumber: 1,
      dayNumber: 1,
      totalDays: totalCurriculum,
      cycle: 1,
      isCycleCompleted: false,
      isPreview: true,
      dateStr,
      formattedDate: getISTFormattedDate(dateStr),
    };
  }

  const cycle = Math.floor(diffDays / totalCurriculum) + 1;
  const challengeIndex = diffDays % totalCurriculum;
  const dayNumber = diffDays + 1;
  const sequenceNumber = challengeIndex + 1;
  const isCycleCompleted = cycle > 1;

  const challenge = DAILY_CHALLENGES[challengeIndex] || DAILY_CHALLENGES[0];

  return {
    challenge,
    sequenceNumber,
    dayNumber,
    totalDays: totalCurriculum,
    cycle,
    isCycleCompleted,
    isPreview: false,
    dateStr,
    formattedDate: getISTFormattedDate(dateStr),
  };
}

/**
 * Returns tomorrow's challenge preview for the Up Next card.
 */
export function getUpcomingChallenge(targetDateStr?: string): { challenge: DailyChallenge; sequenceNumber: number; dayNumber: number; dateStr: string } {
  const currentDate = targetDateStr || getISTDateString();
  const [y, m, d] = currentDate.split('-').map(Number);
  const nextDay = new Date(Date.UTC(y, m - 1, d + 1));
  const nextDateStr = nextDay.toISOString().split('T')[0];

  const info = getDailyChallengeByDate(nextDateStr);
  return {
    challenge: info.challenge,
    sequenceNumber: info.sequenceNumber,
    dayNumber: info.dayNumber,
    dateStr: nextDateStr,
  };
}

export function getAllDailyChallenges(): DailyChallenge[] {
  return DAILY_CHALLENGES;
}

export function getDailyChallengeBySequence(sequenceNumber: number): DailyChallenge | undefined {
  return DAILY_CHALLENGES.find((c) => c.sequenceNumber === sequenceNumber);
}
